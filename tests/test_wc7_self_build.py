        data = parse_roadmap()
        
        assert "items" in data
        assert "next_unshipped" in data
        assert len(data["items"]) >= 2
        
        # Check shipped items
        wc1 = next((item for item in data["items"] if item["id"] == "WC-1"), None)
        assert wc1 is not None
        assert wc1["shipped"] is True
        assert wc1["name"] == "True Parallel Multi-Agent"
        
        wc2 = next((item for item in data["items"] if item["id"] == "WC-2"), None)
        assert wc2 is not None
        assert wc2["shipped"] is True
    

class TestIntegration:
    """Integration tests."""
    
    @patch("openbot.routines.attach_routine_cron")
    def test_full_flow_enable_to_routine(self, mock_attach_cron, temp_roadmap):
        """Full flow: enable setting → create routine → attach cron."""
        mock_attach_cron.return_value = {"ok": True}
        
        # Start disabled
        save_settings({"enable_self_build": False})
        assert self_build_enabled() is False
        
        # Enable
        save_settings({"enable_self_build": True})
        result = ensure_self_build_routine()
        
        assert result["ok"] is True
        assert result["action"] in {"created", "exists"}
        
        # Verify routine created
        routine = read_routine("routine-selfbuild", None)
        assert routine is not None
        assert routine["enabled"] is True
        
        # Verify cron attached
        if result["action"] == "created":
            mock_attach_cron.assert_called_once_with("routine-selfbuild", None)
        
        # Cleanup
        save_settings({"enable_self_build": False})
        ensure_self_build_routine()


